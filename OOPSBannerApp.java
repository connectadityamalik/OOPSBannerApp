public class OOPSBannerApp {
    public static void main(String[] args) {
        // UC3 Goal: Use String.join() with an empty delimiter "" [cite: 158, 161]
        System.out.println(String.join("", "  *** ", "   *** ", " ***** ", "  **** "));
        System.out.println(String.join("", " * * ", "  * * ", " * * ", " * "));
        System.out.println(String.join("", " * * ", "  * * ", " * * ", " * "));
        System.out.println(String.join("", " * * ", "  * * ", " ***** ", "  *** "));
        System.out.println(String.join("", " * * ", "  * * ", " * ", "     * "));
        System.out.println(String.join("", " * * ", "  * * ", " * ", "     * "));
        System.out.println(String.join("", "  *** ", "   *** ", " * ", " **** "));
    }
}
